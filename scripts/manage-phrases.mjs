// Collects the fixed sentences of the management phone line (ivr/flow.js + engine.js) for recordings:
// text('...'), number(['...']), menu / listChoice titles, end(c, '...') and menu items ("ל<label>").
// Run: node scripts/manage-phrases.mjs > api/src/ivr/managePhrases.js   (a test checks it is up to date)
import { readFileSync } from 'node:fs';

export function extract(sources) {
  const out = new Set();
  const hebrew = /[֐-׿]/;
  const add = (s) => { const t = s.trim(); if (t && hebrew.test(t) && !t.includes('${') && !/^[,.]/.test(t)) out.add(t); };
  for (const src of sources) {
    for (const m of src.matchAll(/\btext\('([^'\n]+)'\)/g)) add(m[1]);
    for (const m of src.matchAll(/\bend\(c, '([^'\n]+)'\)/g)) add(m[1]);
    for (const m of src.matchAll(/\b(?:menu|listChoice|numberedList)\((?:c, )?'([^'\n]+)'/g)) add(m[1]);
    for (const m of src.matchAll(/\bnumber\(\[([^\]]+)\]/g)) for (const s of m[1].matchAll(/'([^'\n]+)'/g)) add(s[1]);
    for (const m of src.matchAll(/\['[0-9*#]', '([^'\n]+)'\]/g)) add(`ל${m[1]}`); // menu item: "ל<label> הקישו <d>"
    for (const m of src.matchAll(/zero: '([^'\n]+)'/g)) add(`ל${m[1]}`);
  }
  return [...out].sort((a, b) => a.localeCompare(b, 'he'));
}

export const render = (list) => `// Generated by scripts/manage-phrases.mjs from ivr/flow.js and ivr/engine.js — do not edit by hand.
// The fixed sentences of the management line; each can be recorded (voice.js).
export const MANAGE_PHRASES = ${JSON.stringify(list, null, 2).replace(/"/g, "'")};
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = new URL('../api/src/ivr/', import.meta.url);
  process.stdout.write(render(extract(['flow.js', 'engine.js'].map((f) => readFileSync(new URL(f, dir), 'utf8')))));
}
